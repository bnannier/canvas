import { type ComponentType, type ReactNode } from "react";
import type { IconName } from "@nannier/canvas";
import type { ExampleScope } from "../scope";
import type { Section } from "./detail-sections";

export type { Section };

export interface ComponentDoc {
  slug: string;
  name: string;
  // No description here: a component's description is the first paragraph of its .md
  // intro, generated into docs/src/core/descriptions.ts (componentDescription).
  category: Category;
  // The v4 hand-off's section (room) for the component ("Controls", "Inputs", ...), joined
  // on from docs/src/core/data/detail-sections.ts (generated by `bun run v4:specs`).
  section: Section;
  // Source directory under src/<level>/, when it differs from the URL slug.
  // Used when one docs page covers multiple exports (e.g. the Row & Column
  // page reads /components/row-column while loading from src/atoms/layout/).
  // Defaults to slug when omitted.
  dir?: string;
  // How the live preview positions the example within each platform row.
  // `center` (the default) shrink-wraps the example and centers it, which is
  // right for naturally-sized atoms (Button, Badge, Avatar). `start` makes the
  // example fill the row width and align to the leading edge, which is right for
  // block-level, leading-aligned components (Breadcrumb is a full-width nav trail
  // that reads from the left and should never preview centered).
  stageAlign?: "center" | "start";
  // Render ONE live preview instead of the stacked iOS/Android/Web 3-up. Right for a
  // component that IS full app chrome and reads as a single product surface rather than a
  // per-OS specimen to compare (Sidebar, whose example is a whole responsive app shell).
  // No-op on native, where the stage is already a single device preview.
  singlePreview?: boolean;
}

export type Category =
  | "Atoms"
  | "Molecules"
  | "Organisms"
  | "Charts";

/** A live example whose named component owns its state. */
export interface DocSection {
  title: string;
  description?: string;
  anatomy?: string;
  render: () => ReactNode;
}

/** The device a template's screen is framed in: a browser window, an iPhone or a Pixel. */
export type TemplatePlatform = "web" | "ios" | "android";

/** The hand-off's template groups (`Canvas v4.0.0 Templates.dc.html` TPLS), in order. */
export type TemplateGroup = "Auth" | "App" | "Account" | "States";

/** What a template's screen is rendered with inside its device frame. */
export interface TemplateScreenProps {
  /**
   * The kit as the frame's platform draws it: every Canvas export with that platform's
   * skins in place (docs/src/core/build-scopes), so one tree renders the web, iOS and
   * Android looks. A screen takes every component it renders from here.
   */
  K: ExampleScope;
  /** The frame is a phone: its app bar names the screen, so a screen drops its own heading. */
  phone: boolean;
  /** Opens another template in the frame (a link between screens: Create an account, View all). */
  go: (slug: string) => void;
}

/**
 * One template of the hand-off's Templates page: a whole product screen composed from
 * live Canvas components, shown in a browser window, an iPhone or a Pixel.
 */
export interface TemplateDoc {
  slug: string;
  name: string;
  group: TemplateGroup;
  /** The kit glyph the template list shows beside the name. */
  icon: IconName;
  /** The hand-off's one-line description, shown under the template's name. */
  description: string;
  /** The path the browser frame's address bar shows after `app.riskora.com/`. */
  path: string;
  /** The screen sits in the Riskora app's chrome: the sidebar and top bar on the web, the app bar and tab bar on a phone. */
  app: boolean;
  Screen: ComponentType<TemplateScreenProps>;
}

export type PatternSection = DocSection;

export interface PatternDoc {
  slug: string;
  name: string;
  description: string;
  sections: PatternSection[];
}

export interface SearchEntry {
  title: string;
  description: string;
  path: string;
  category: string;
  keywords: string[];
  /** A component's page: search ranks these above every other kind of entry. */
  component?: boolean;
}
