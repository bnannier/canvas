import { type ReactNode } from "react";
import { Button, Column, DataTable, Typography } from "@nannier/canvas";
import { useRouter } from "expo-router";
import { Page, PageHeader } from "../../ui/page";
import { Section } from "../../ui/section";
import { BulletList, InlineCode, P, Paragraph } from "../../ui/prose";
import { CodeBlock } from "../../ui/code-block";
import { Callout } from "../../ui/tokens-kit";
import { PageNav } from "../../ui/page-nav";
import { DEPRECATED_SECTIONS, type DeprecatedName, type DeprecatedSectionTitle } from "../../core/foundation-reference";

// The foundation reference (audit K12-10, the owner's OD2 decision): every deprecated name
// of the kit, what it was and what to use instead. The rows are generated by docs:gen from
// tools/api/manifest.ts and the source (docs/src/core/foundation-reference.ts), so the page
// cannot drift from either; check:api reads them as part of this page and fails when a
// deprecated alias is missing here. What is written by hand is the frame around them: the
// intro, the contract notes some sections carry, and the Accessibility section.

const MIGRATION = `// Before: the helper the kit used for its own figures
<Text style={tabularNums()}>1,204,118</Text>

// After: the component's own prop
<Typography tabular>1,204,118</Typography>`;

// The contracts the deprecated machinery carried, which the components that replace it
// keep (the AnchoredOverlay, Entrance, FloatingLabel and BreakpointOverride turns' notes).
const NOTES: Partial<Record<DeprecatedSectionTitle, ReactNode>> = {
  "Overlay machinery": (
    <Callout label="What the anchored card does for every menu and Popover">
      A card opens below its trigger by default, above or beside it on request, and stays inside the window&apos;s visible area and safe area. A tap outside and Android&apos;s back close it, and Escape closes the foremost one on the web. On iOS and Android an open card is modal to VoiceOver and TalkBack and returns focus to its trigger when it closes. On the web a menu or option list moves focus in and Tab closes it and moves on, while a Popover stays non-modal. At phone width Popover opens as a sheet; menus, Select and Autocomplete stay anchored. In a right-to-left app a card follows the app&apos;s direction.
    </Callout>
  ),
  Entrance: (
    <Callout label="Testing an anchored card">
      A card stays invisible, untouchable and hidden from assistive technology until its placement is measured, then appears in place with no motion. A test DOM with no layout (no ResizeObserver) never measures a card hosted by an OverlayProvider, so it never shows: render the component without an OverlayProvider in such a test, where the card renders inline.
    </Callout>
  ),
  "Field label": (
    <Callout label="The label contract of Input, Textarea, Select and Autocomplete">
      Android floats the label inside the field; iOS and the web title the field from above. The label is the field&apos;s accessible name, and natively never a second stop beside it. The required star is decorative and never part of the name: the field says it is required. A long label truncates on one line while the name stays whole. The float follows the user&apos;s text size, and under Reduce Motion it moves without animating.
    </Callout>
  ),
  "Viewport tier": (
    <Callout label="Server rendering and the window">
      A server cannot measure a window, so it renders the desktop layout unless ThemeProvider&apos;s ssrBreakpoint names the bucket to assume (sm for a phone); the real window&apos;s bucket applies right after hydration. Window-level chrome reads the tier with useBreakpoint or useFormFactor, and a component measures its own width with useContainerWidth or useMeasuredWidth.
    </Callout>
  ),
};

// The name column holds one identifier, the longest about 30 characters of the mono face,
// so it takes that width and the two prose columns share the rest. Stacked at phone width
// every column takes the full row.
const COLUMNS = [{ label: "Name", width: 264 }, "What it was", "Use instead"];

function NameCell({ row }: { row: DeprecatedName }) {
  return (
    <Column flush>
      <InlineCode>{row.name}</InlineCode>
      {row.type ? <Typography tiny subtle>Type</Typography> : null}
    </Column>
  );
}

function InsteadCell({ row }: { row: DeprecatedName }) {
  const router = useRouter();
  const href = row.replacementRoute ? `/${row.replacementRoute}` : null;
  return (
    <Column tight>
      <Paragraph small text={row.instead} />
      {href && row.replacement ? (
        <Button link small href={href} onPress={() => router.push(href as never)}>{`See ${row.replacement}`}</Button>
      ) : null}
    </Column>
  );
}

export default function FoundationScreen() {
  return (
    <Page>
      <PageHeader title="Foundation reference" description="Every deprecated name in Canvas, what it was and what to use instead." />
      <Section title="How deprecation works">
        <P>Canvas once published some of its own machinery: the helpers its components build themselves from. Each of those names is now a deprecated alias. It keeps working, unchanged, until a major release, and nothing is removed before one. Your editor strikes it through, and its hover says what to use instead.</P>
        <P muted>Where one component, prop or token replaces a name, the row links to its page. A name with no replacement is work the kit&apos;s components already do for you; a control the kit lacks belongs in the kit, never in a hand-built look-alike.</P>
        <CodeBlock code={MIGRATION} />
      </Section>
      {DEPRECATED_SECTIONS.map((section) => (
        <Section key={section.title} title={section.title}>
          <P muted>{section.about}</P>
          {NOTES[section.title] ?? null}
          <DataTable
            bordered
            stacks
            columns={COLUMNS}
            rows={section.names.map((row) => [
              <NameCell key="name" row={row} />,
              <Paragraph key="was" small text={row.summary} />,
              <InsteadCell key="instead" row={row} />,
            ])}
          />
        </Section>
      ))}
      <Section title="Accessibility">
        <P>The deprecated names were the machinery behind the kit&apos;s keyboard, screen reader and touch behaviour, and the components that replace them keep all of it.</P>
        <BulletList
          items={[
            "**Keyboard.** Tabs, RadioGroup and Listbox are one Tab stop each: the arrow keys move and select, Home and End take the first and last option, and a disabled option is skipped and is never the stop. Dialog and AlertDialog hold Tab inside and return focus to what opened them, a Popover moves focus in and back, and Escape closes the foremost overlay on the web.",
            "**Screen readers.** On iOS and Android an open menu, option list or Popover is modal to VoiceOver and TalkBack and returns focus to its trigger, and a card still being placed is hidden from them. A field's label is its accessible name, never a second stop, and its required star is not read. Decorative content is hidden on all three platforms.",
            "**Touch.** Every kit control meets the 44 pt (iOS) and 48 dp (Android) minimum from its first frame by growing its touch area, never its shape, and Android's back closes an open overlay. Where two touch areas overlap the later one takes the tap, so leave twice the extra area between two small controls you place side by side.",
            "**Focus and motion.** Every control keeps the themed focus ring, and only a field that paints its own focus state replaces it. The kit's functional motion follows Reduce Motion.",
          ]}
        />
      </Section>
      <PageNav />
    </Page>
  );
}
