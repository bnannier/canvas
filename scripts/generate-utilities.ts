// Escape a utility class name so the authored selector matches the literal class
// attribute. Three cases:
//   - ":" is the breakpoint separator (md:flex)  -> "\:"
//   - "/" appears in fractional names (w-1/2)     -> "\/"
//   - a LEADING digit is invalid at the start of a CSS identifier, so the "2" in
//     "2xl:flex" must be escaped as a code point ("\32 " incl. trailing space),
//     otherwise the browser drops the whole rule.
function escapeClass(name: string): string {
  let out = "";
  for (let i = 0; i < name.length; i++) {
    const ch = name[i];
    if (i === 0 && ch >= "0" && ch <= "9") {
      out += "\\3" + ch + " ";
    } else if (ch === ":" || ch === "/") {
      out += "\\" + ch;
    } else {
      out += ch;
    }
  }
  return out;
}

function emitRule(cls: string, decl: string, indent: string): string {
  return `${indent}.${escapeClass(cls)} { ${decl}; }`;
}

function emitGroup(group: Group): string {
  const lines: string[] = [BANNER, "@layer canvas.utilities {"];

  for (const r of group.rules) {
    lines.push(emitRule(r.cls, r.decl, "  "));
  }

  if (group.responsive) {
    for (const [bp, min] of BREAKPOINTS) {
      lines.push("");
      lines.push(`  @media (min-width: ${min}px) {`);
      for (const r of group.rules) {
        lines.push(emitRule(`${bp}:${r.cls}`, r.decl, "    "));
      }
      lines.push("  }");
    }
  }

  lines.push("}");
  lines.push("");
  return lines.join("\n");
}

async function main(): Promise<void> {
  // Guardrail: every gap utility must reference a token that actually exists.
  const spacingCss = await readFile(join(STYLES_DIR, "tokens", "spacing.css"), "utf-8");
  const definedSpace = new Set(
    [...spacingCss.matchAll(/--space-([\w-]+)\s*:/g)].map((m) => m[1]),
  );
  for (const v of SPACE_SCALE) {
    if (!definedSpace.has(v)) {
      throw new Error(
        `gap utility references --space-${v}, which is not defined in styles/tokens/spacing.css`,
      );
    }
  }

  await mkdir(OUT_DIR, { recursive: true });

  for (const group of GROUPS) {
    const css = emitGroup(group);
    await writeFile(join(OUT_DIR, `${group.file}.css`), css, "utf-8");
  }

  const baseCount = GROUPS.reduce((n, g) => n + g.rules.length, 0);
  const total = GROUPS.reduce(
    (n, g) => n + g.rules.length * (g.responsive ? BREAKPOINTS.length + 1 : 1),
    0,
  );
  console.log(
    `Generated ${GROUPS.length} utility files (${baseCount} base classes, ${total} rules total) in styles/utilities/`,
  );
}

await main();
