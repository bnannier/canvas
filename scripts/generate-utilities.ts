interface Rule {
  cls: string; // logical class name, unescaped (e.g. "flex", "w-1/2", "gap-0-5")
  decl: string; // declaration body, no trailing semicolon (e.g. "display:flex")
}

interface Group {
  file: string; // output filename stem under styles/utilities/
  responsive: boolean; // emit sm/md/lg/xl/2xl variants?
  rules: Rule[];
}

function span(n: number): Rule {
  return { cls: `col-span-${n}`, decl: `grid-column:span ${n} / span ${n}` };
}
function cols(n: number): Rule {
  return { cls: `grid-cols-${n}`, decl: `grid-template-columns:repeat(${n}, minmax(0, 1fr))` };
}

