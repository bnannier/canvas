/**
 * Generates the Canvas layout utility layer as static, plain-CSS files under
 * styles/utilities/. Run via `bun run generate-utilities`.
 *
 * Why a generator: the utility set is ~140 base classes, each repeated across 5
 * responsive breakpoints (~840 rules). Hand-maintaining that is error-prone. This
 * script is an authoring-time tool (like the other scripts/*.ts); the OUTPUT it
 * commits is ordinary CSS, so consumers still need no build step.
 *
 * Output is deterministic: groups in config order, base rules before responsive,
 * breakpoints ascending. Re-running produces a zero git diff. CI enforces that the
 * committed files match what this script produces.
 */
