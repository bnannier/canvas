// Mirrors the v4 hand-off's text colors as literals for the native token table.
// D14 removes contrast-driven recoloring. The legacy solved-inks filename and constant
// remain internal tooling names; these values are direct reference colors, never solved.
//
//   bun run tokens:inks            write src/style/solved-inks.ts
//   bun run tokens:inks:check      check the generated reference table
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { oklchHex } from "../../src/style/color.ts";
import { ACCENT, NEUTRALS, PALETTES, SERIES, paletteHue, type ColorScheme, type InkRole, type Palette } from "../../src/style/tokens.ts";

const OUT = join(import.meta.dir, "../../src/style/solved-inks.ts");
export const HUE_TONES = { cyan: 0, mint: 1 } as const;
export type HueTone = keyof typeof HUE_TONES;

export interface SchemeInks {
  status: Record<InkRole, string>;
  "primary-text": Record<Palette, string>;
  "inverse-primary": Record<Palette, string>;
  hues: Record<HueTone, string>;
}

/** Direct text aliases and formulas from the component hand-off. */
export function referenceInks(): Record<ColorScheme, SchemeInks> {
  const scheme = (s: ColorScheme): SchemeInks => {
    const a = ACCENT[s];
    const other = ACCENT[s === "dark" ? "light" : "dark"];
    const perPalette = (text: readonly [number, number]) => Object.fromEntries(
      PALETTES.map((p) => [p, oklchHex(text[0], text[1], paletteHue[p])]),
    ) as Record<Palette, string>;
    const n = NEUTRALS[s];
    return {
      status: { "destructive-text": n.destructive, "success-text": n.success, "warning-text": n.warning },
      "primary-text": perPalette(a.text),
      "inverse-primary": perPalette(other.text),
      hues: Object.fromEntries((Object.keys(HUE_TONES) as HueTone[]).map((tone) => {
        const [l, c, h] = SERIES[s][HUE_TONES[tone]]!;
        return [tone, oklchHex(l, c, h)];
      })) as Record<HueTone, string>,
    };
  };
  return { light: scheme("light"), dark: scheme("dark") };
}

export function renderInks(): string {
  const inks = referenceInks();
  const record = (r: Record<string, string>, indent: string) =>
    `{\n${Object.entries(r).map(([k, v]) => `${indent}  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n")}\n${indent}}`;
  const scheme = (s: ColorScheme) => {
    const i = inks[s];
    return `  ${s}: {\n    status: ${record(i.status, "    ")},\n    "primary-text": ${record(i["primary-text"], "    ")},\n    "inverse-primary": ${record(i["inverse-primary"], "    ")},\n    hues: ${record(i.hues, "    ")},\n  },`;
  };
  return [
    "// GENERATED by tools/v4/derive-inks.ts (`bun run tokens:inks`); do not edit by hand.",
    "// Direct v4 hand-off text colors (D14), without contrast-driven recoloring.",
    "// The internal constant name is retained for tooling compatibility.",
    "",
    "export const SOLVED_INKS = {",
    scheme("light"), scheme("dark"), "} as const;", "",
  ].join("\n");
}

if (import.meta.main) {
  const text = renderInks();
  if (process.argv.includes("--check")) {
    if (readFileSync(OUT, "utf-8") !== text) {
      console.error("src/style/solved-inks.ts is stale: run `bun run tokens:inks`.");
      process.exit(1);
    }
    console.log("tokens:inks --check: the text colors match the hand-off formulas.");
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT}`);
  }
}
